export function getCategoryDotColor(category) {
  const text = String(category || "");
  if (!text || text === "—" || text === "ทั่วไป") return "#64748b"; // gray default
  
  let hash = 0;
  for (let i = 0; i < text.length; i++) {
    hash = text.charCodeAt(i) + ((hash << 5) - hash);
  }
  
  const dotColors = [
    "#ea580c", // Orange
    "#d97706", // Amber
    "#059669", // Emerald
    "#0d9488", // Teal
    "#0284c7", // Sky
    "#7c3aed", // Violet
    "#e11d48", // Rose
    "#15803d", // Green
    "#7e22ce", // Purple
    "#14b8a6"  // Dark Teal
  ];
  
  const index = Math.abs(hash) % dotColors.length;
  return dotColors[index];
}

export function getCategoryBadgeStyle(idOrName) {
  if (badgeColors[idOrName]) return badgeColors[idOrName];
  
  const text = String(idOrName || "");
  if (!text || text === "—" || text === "ทั่วไป") {
    return { bg: "#f1f5f9", text: "#334155", border: "#e2e8f0", dot: "#64748b" }; // gray fallback
  }

  let hash = 0;
  for (let i = 0; i < text.length; i++) {
    hash = text.charCodeAt(i) + ((hash << 5) - hash);
  }
  
  const presets = [
    { bg: "#fff7ed", text: "#c2410c", border: "#ffedd5", dot: "#ea580c" }, // Orange
    { bg: "#fefbeb", text: "#b45309", border: "#fef3c7", dot: "#d97706" }, // Amber
    { bg: "#ecfdf5", text: "#047857", border: "#a7f3d0", dot: "#059669" }, // Emerald
    { bg: "#f0fdfa", text: "#0f766e", border: "#99f6e4", dot: "#0d9488" }, // Teal
    { bg: "#f0f9ff", text: "#0369a1", border: "#bae6fd", dot: "#0284c7" }, // Sky
    { bg: "#f5f3ff", text: "#6d28d9", border: "#ddd6fe", dot: "#7c3aed" }, // Violet
    { bg: "#fff1f2", text: "#be123c", border: "#ffe4e6", dot: "#e11d48" }, // Rose
    { bg: "#f0fdf4", text: "#166534", border: "#bbf7d0", dot: "#15803d" }, // Green
    { bg: "#faf5ff", text: "#6b21a8", border: "#e9d5ff", dot: "#7e22ce" }, // Purple
    { bg: "#f0fdfa", text: "#115e59", border: "#99f6e4", dot: "#14b8a6" }  // Dark Teal
  ];
  
  const index = Math.abs(hash) % presets.length;
  const preset = presets[index];
  return { ...preset, dot: getCategoryDotColor(idOrName) };
}
