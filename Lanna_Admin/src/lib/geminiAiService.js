export async function translateWithAi(thaiText) {
  const cleanInput = (thaiText || '').trim();
  if (!cleanInput) {
    throw new Error('กรุณาระบุคำภาษาไทยก่อนแปลงด้วย AI');
  }

  // 1. พยายามเรียกใช้ Gemini API ตามลำดับโมเดลแบบเดียวกับใน Flutter
  for (const model of MODELS) {
    try {
      const url = `https://generativelanguage.googleapis.com/v1beta/models/${model}:generateContent?key=${API_KEY}`;
      const res = await fetch(url, {
        method: 'POST',
        headers: { 'Content-Type': 'application/json' },
        body: JSON.stringify({
          contents: [
            {
              parts: [
                {
                  text: `${PROMPT_INSTRUCTIONS}\n\nข้อความภาษาไทยที่ต้องการแปล: "${cleanInput}"`
                }
              ]
            }
          ]
        })
      });

      if (res.ok) {
        const json = await res.json();
        const rawText = json?.candidates?.[0]?.content?.parts?.[0]?.text;
        if (rawText) {
          const cleanJson = rawText.replace(/```json/g, '').replace(/```/g, '').trim();
          const parsed = JSON.parse(cleanJson);
          const kamMueang = (parsed.kam_mueang || cleanInput).replace(/[\[\]]/g, '').trim();
          const reading = (parsed.phonetic || kamMueang).replace(/[\[\]]/g, '').trim();
          const notation = parsed.lanna_notation || kamMueang;
          const lannaWord = parseLannaNotation(notation, cleanInput);
          const meaning = parsed.meaning || 'แปลและจัดอักขรวิธีล้านนาด้วย AI';

          return {
            kam_mueang: kamMueang,
            reading: reading,
            lanna_word: lannaWord,
            meaning: meaning,
            model: model,
          };
        }
      }
    } catch (err) {
      console.warn(`Gemini model ${model} error:`, err);
    }
  }

  // 2. Fallback: ใช้กฎการแปลคำเมืองและอักขรวิธี LN-TILOK ออฟไลน์ แบบเดียวกับ Flutter
  console.info('Using offline Kam Mueang engine fallback');
  const offline = translateKamMueangOffline(cleanInput);
  return {
    kam_mueang: offline.kam_mueang,
    reading: offline.reading.replace(/[\[\]]/g, ''),
    lanna_word: offline.lanna_word,
    meaning: offline.meaning || 'แปลตามหลักไวยากรณ์และอักขรวิธีคำเมือง',
    fallback: true,
  };
}
